package com.ysulab.yapper.vault;

import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import java.util.TreeSet;

/**
 * Builds {@code _yapper/index.md}: every note's path, title, aliases and top headings, so the sorter
 * can route into notes that already exist. Pure Java; the SAF walk lives in {@link SafVaultFs}.
 */
public final class VaultIndex {

    public static final String APP_DIR = "_yapper";
    public static final String INDEX_PATH = APP_DIR + "/index.md";
    public static final String RULES_PATH = APP_DIR + "/rules.md";
    static final int MAX_HEADINGS = 8;

    private VaultIndex() {}

    /** Folders and files the index (and the sorter) never look at. */
    public static boolean skip(String path) {
        String p = path.toLowerCase(Locale.ROOT);
        if (hidden(p) || SyncSafety.isSyncArtifact(p)) {
            return true; // .obsidian, .trash, .stfolder; Syncthing conflict copies and temp files
        }
        return p.startsWith(APP_DIR + "/") || p.equals(APP_DIR)
                || p.startsWith(InboxNote.INBOX_DIR.toLowerCase(Locale.ROOT) + "/");
    }

    /** True if any path segment starts with a dot (.obsidian, .trash, .git, .stfolder...). */
    public static boolean hidden(String path) {
        for (String seg : path.split("/")) {
            if (seg.startsWith(".")) {
                return true;
            }
        }
        return false;
    }

    /** One line per note, e.g. {@code - Uni/Algorithms.md · aliases: Algo · ## Exams, ## Lectures}. */
    public static String entry(String path, String content) {
        List<String> aliases = new ArrayList<>();
        List<String> headings = new ArrayList<>();
        String title = "";
        String text = content == null ? "" : content;
        String[] lines = text.split("\n");
        int i = 0;
        if (lines.length > 0 && lines[0].trim().equals("---")) {
            boolean inAliases = false;
            for (i = 1; i < lines.length; i++) {
                String l = lines[i];
                if (l.trim().equals("---")) {
                    i++;
                    break;
                }
                String t = l.trim();
                if (t.toLowerCase(Locale.ROOT).startsWith("aliases:") || t.toLowerCase(Locale.ROOT).startsWith("alias:")) {
                    String v = t.substring(t.indexOf(':') + 1).trim();
                    inAliases = v.isEmpty();
                    if (!v.isEmpty()) {
                        v = v.replaceAll("^\\[|\\]$", "");
                        for (String a : v.split(",")) {
                            addClean(aliases, a);
                        }
                    }
                } else if (inAliases && t.startsWith("- ")) {
                    addClean(aliases, t.substring(2));
                } else {
                    inAliases = false;
                }
            }
        }
        boolean fence = false;
        for (; i < lines.length; i++) {
            String t = lines[i].trim();
            if (t.startsWith("```")) {
                fence = !fence;
                continue;
            }
            if (fence) {
                continue;
            }
            if (title.isEmpty() && t.startsWith("# ")) {
                title = t.substring(2).trim();
            } else if ((t.startsWith("## ") || t.startsWith("### ")) && headings.size() < MAX_HEADINGS) {
                String h = t.replaceAll("%%.*?%%", "").trim();
                // Dated headings Yapper writes are noise for routing.
                if (!h.matches("#+ \\d{4}-\\d{2}-\\d{2}.*") && !headings.contains(h)) {
                    headings.add(h);
                }
            }
        }
        StringBuilder sb = new StringBuilder("- ").append(path);
        String name = path.substring(path.lastIndexOf('/') + 1).replaceAll("\\.md$", "");
        if (!title.isEmpty() && !title.equals(name)) {
            sb.append(" · title: ").append(title);
        }
        if (!aliases.isEmpty()) {
            sb.append(" · aliases: ").append(String.join(", ", aliases));
        }
        if (!headings.isEmpty()) {
            sb.append(" · ").append(String.join(", ", headings));
        }
        return sb.toString();
    }

    public static String render(List<String> folders, List<String> entries) {
        StringBuilder sb = new StringBuilder();
        sb.append("# Vault index\n\n");
        sb.append("_Auto-generated by Yapper before each capture is sorted. Edits here are overwritten._\n\n");
        sb.append("## Folders\n");
        TreeSet<String> f = new TreeSet<>(folders);
        if (f.isEmpty()) {
            sb.append("(none yet)\n");
        }
        for (String d : f) {
            sb.append("- ").append(d).append("/\n");
        }
        sb.append("\n## Notes\n");
        TreeSet<String> e = new TreeSet<>(entries);
        if (e.isEmpty()) {
            sb.append("(none yet)\n");
        }
        for (String line : e) {
            sb.append(line).append('\n');
        }
        return sb.toString();
    }

    private static void addClean(List<String> out, String raw) {
        String a = raw.trim().replaceAll("^[\"']|[\"']$", "").trim();
        if (!a.isEmpty()) {
            out.add(a);
        }
    }
}
